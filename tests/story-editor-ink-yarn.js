#!/usr/bin/env node
/*
 * tests/story-editor-ink-yarn.js
 * A1594: the Story Editor must export valid Ink (.ink) and Yarn Spinner (.yarn)
 * scripts alongside its own JSON / Godot / Unity output.
 * Run: node tests/story-editor-ink-yarn.js
 */
const http = require('http');
const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer');

const ROOT = path.join(__dirname, '..');
const PORT = process.env.SEIY_PORT || 9001;
const BASE = `http://localhost:${PORT}/`;
const MIME = { '.html':'text/html', '.js':'text/javascript', '.css':'text/css', '.json':'application/json',
  '.png':'image/png', '.jpg':'image/jpeg', '.webp':'image/webp', '.woff2':'font/woff2', '.mjs':'text/javascript' };

let failures = 0;
function check(name, ok, detail){ console.log((ok?'PASS ':'FAIL ')+name+(detail?' , '+detail:'')); if(!ok) failures++; }

(async () => {
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent(req.url.split('?')[0]);
    let file = p; if (file.endsWith('/')) file += 'index.html';
    fs.readFile(path.join(ROOT, file), (err, buf) => {
      if (err) { res.writeHead(404); res.end(); return; }
      res.writeHead(200, { 'Content-Type': MIME[path.extname(file).toLowerCase()] || 'application/octet-stream' });
      res.end(buf);
    });
  }).listen(PORT);

  const browser = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push(e.message));
  await page.setViewport({ width: 1440, height: 900 });
  await page.goto(BASE + 'tools/story-editor.html', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => typeof _storyToInk === 'function' && Array.isArray(nodes) && nodes.length > 0, { timeout: 20000 });

  const r = await page.evaluate(() => ({
    ink: _storyToInk(),
    yarn: _storyToYarn(),
    hasInkBtn: !!document.querySelector('[data-on="exportInk"]'),
    hasYarnBtn: !!document.querySelector('[data-on="exportYarn"]'),
    hasGodotBtn: !!document.querySelector('[data-on="exportGodot"]')
  }));

  // Ink
  check('Ink has the header comment', r.ink.startsWith('// Generated by JVDesignStudio'));
  check('Ink declares global variables (VAR)', /VAR respect = 0/.test(r.ink));
  check('Ink emits knots', /=== n1 ===/.test(r.ink) && /=== n3 ===/.test(r.ink));
  check('Ink diverts between nodes', /-> n2\b/.test(r.ink));
  check('Ink has at least one choice', /\* /.test(r.ink));
  check('Ink has an END', /-> END/.test(r.ink));
  check('Ink tags the speaker', /# char: Wizard/.test(r.ink));

  // Yarn Spinner
  check('Yarn has node headers', /title: n1\b/.test(r.yarn) && /---/.test(r.yarn) && /===/.test(r.yarn));
  check('Yarn declares variables', /<<declare \$respect = 0>>/.test(r.yarn));
  check('Yarn jumps between nodes', /<<jump n2>>/.test(r.yarn));
  check('Yarn has at least one option', /\n-> /.test(r.yarn));
  check('Yarn names the speaker', /Wizard: /.test(r.yarn));
  check('Yarn stops at an ending', /<<stop>>/.test(r.yarn));

  // Buttons + layout
  check('Ink + Yarn export buttons exist', r.hasInkBtn && r.hasYarnBtn && r.hasGodotBtn);
  check('no uncaught JS errors', errs.length === 0, errs.slice(0, 2).join(' | '));

  await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await new Promise(r => setTimeout(r, 250));
  const m = await page.evaluate(() => ({
    ink: !!document.querySelector('[data-on="exportInk"]'),
    yarn: !!document.querySelector('[data-on="exportYarn"]'),
    noScroll: document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1
  }));
  check('390px: Ink + Yarn buttons present', m.ink && m.yarn);
  check('390px: no horizontal scroll', m.noScroll === true);

  await browser.close();
  server.close();
  if (failures) { console.log('\n' + failures + ' FAILURE(S)'); process.exit(1); }
  console.log('\nALL STORY EDITOR INK/YARN CHECKS PASSED');
})().catch(e => { console.error(e); process.exit(1); });
