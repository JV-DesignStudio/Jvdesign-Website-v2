#!/usr/bin/env node
/*
 * scripts/sync-arcade-maker-modules.js , A759
 *
 * The modular split of tools/arcade-game-maker.html keeps three copies of some
 * data: the live inline definitions in the HTML (source of truth until A760
 * wires the modules up) and the ES-module scaffolds under src/arcade-maker/.
 * Those copies drift, so this script rebuilds the scaffolds from the live HTML
 * with a deterministic transform. The matching test
 * (tests/arcade-maker-modules-sync.js) then seals them so they cannot drift
 * again: re-run this after any edit to the inline liveConfig/GameAudio.
 *
 * Usage:
 *   node scripts/sync-arcade-maker-modules.js            # write the modules
 *   node scripts/sync-arcade-maker-modules.js --check    # exit 1 if out of date
 *   node scripts/sync-arcade-maker-modules.js --stdout   # print, do not write
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const HTML = path.join(ROOT, 'tools', 'arcade-game-maker.html');
const SRC_DIR = path.join(ROOT, 'src', 'arcade-maker');
const LF = '\n';

function readHtml() {
  return fs.readFileSync(HTML, 'utf8');
}

function lineIndexOf(lines, pred, from) {
  for (let i = from || 0; i < lines.length; i++) if (pred(lines[i], i)) return i;
  return -1;
}

// First line whose trimmed text equals `text`, at or after `from`.
function exact(lines, text, from) {
  const i = lineIndexOf(lines, l => l.trim() === text, from);
  if (i === -1) throw new Error('marker not found: ' + text);
  return i;
}

function seg(lines, a, b) { return lines.slice(a, b + 1).join(LF); }

// Find the line that closes an object literal opened on `startLine` by scanning
// brace depth, ignoring braces inside strings/comments. Returns the terminating
// `};` line so nested `};` (e.g. inside a function body) is never mistaken for it.
function findObjectEnd(lines, startLine) {
  let depth = 0, started = false;
  for (let i = startLine; i < lines.length; i++) {
    const line = lines[i];
    let inS = null, esc = false, inLC = false, inBC = false;
    for (let j = 0; j < line.length; j++) {
      const ch = line[j], nx = line[j + 1];
      if (inLC) break;
      if (inBC) { if (ch === '*' && nx === '/') { inBC = false; j++; } continue; }
      if (inS) { if (esc) { esc = false; } else if (ch === '\\') { esc = true; } else if (ch === inS) { inS = null; } continue; }
      if (ch === '/' && nx === '/') { inLC = true; break; }
      if (ch === '/' && nx === '*') { inBC = true; j++; continue; }
      if (ch === '"' || ch === "'" || ch === '`') { inS = ch; continue; }
      if (ch === '{') { depth++; started = true; }
      else if (ch === '}') { depth--; if (started && depth === 0) return i; }
    }
  }
  throw new Error('object literal at line ' + (startLine + 1) + ' never closed');
}

function buildLiveConfig(html) {
  const lines = html.split(/\r?\n/);
  const objStart = exact(lines, 'const liveConfig = {');
  const objEnd = findObjectEnd(lines, objStart);

  const tdStart = exact(lines, 'if (!liveConfig.tdStartGold)    liveConfig.tdStartGold    = 150;');
  const tdEnd = exact(lines, 'if (liveConfig.waveClearBonus    === undefined) liveConfig.waveClearBonus    = true;', tdStart);

  const stateStart = exact(lines, 'const gameState = { lives:3 };');
  const clearStart = exact(lines, 'function _clearTouchInput() {', stateStart);
  const themeConst = exact(lines, 'const gameTheme = { cols:[], name:\'\' };', clearStart);
  const themeStart = exact(lines, 'function themeInt(idx, fallback) {', clearStart);
  const themeEnd = exact(lines, 'function themeHex(idx, fallback) { return gameTheme.cols[idx] || fallback; }', themeStart);
  const tdDataStart = exact(lines, 'function _themeData(theme) {', themeEnd);
  const tdDataEnd = lineIndexOf(lines, l => l.trim() === 'return themes[theme] || themes.space;', tdDataStart);
  if (tdDataEnd === -1) throw new Error('_themeData return not found');
  const tdDataClose = lineIndexOf(lines, l => l.trim() === '}', tdDataEnd);

  // Guarded so the module also works standalone (import()), while an inline
  // fallback keeps the same object identities when loaded alongside the HTML.
  const preGuard = 'if (typeof gameState === "undefined") var gameState = { lives:3 };';
  const preTouch = 'if (typeof touchInput === "undefined") var touchInput = { left:false, right:false, up:false, down:false, fire:false, lane0:false, lane1:false, lane2:false, lane3:false };';
  const preTheme = 'if (typeof gameTheme === "undefined") var gameTheme = { cols:[], name:"" };';

  return [
    '// liveConfig.js , GENERATED by scripts/sync-arcade-maker-modules.js from tools/arcade-game-maker.html.',
    '// Canonical ES-module form of the game config, state, theme data and TD defaults.',
    '// Do not hand-edit: edit the inline source and re-run the sync script.',
    '// Import: import { liveConfig, gameState, touchInput, gameTheme, themeInt, themeHex, _themeData } from "./liveConfig.js";',
    '',
    seg(lines, objStart, objEnd),
    '',
    '// Perk-aware accessors: RunMods multipliers fold into speed/fireCooldown at runtime.',
    '/* Player movement speed and weapon cadence are read directly by all 21 scenes,',
    '   so rather than touching ~80 call sites the two values become accessors that',
    "   fold in the current run's perks. The raw author-set numbers live in",
    '   liveConfig._base and are what save/share/export always write, so a run can',
    '   never leak its buffs back into the studio sliders. With no perks taken both',
    '   multipliers are exactly 1 and every genre behaves as it did before. */',
    'liveConfig._base = { speed: liveConfig.speed, fireCooldown: liveConfig.fireCooldown };',
    'Object.defineProperty(liveConfig, "speed", {',
    '    enumerable: true, configurable: true,',
    '    get() { let m = 1; try { m = RunMods.moveSpeedMul; } catch (e) { m = 1; } return this._base.speed * (m || 1); },',
    '    set(v) { this._base.speed = v; },',
    '});',
    'Object.defineProperty(liveConfig, "fireCooldown", {',
    '    enumerable: true, configurable: true,',
    '    get() { let m = 1; try { m = RunMods.fireRateMul; } catch (e) { m = 1; } return Math.max(24, Math.round(this._base.fireCooldown / (m || 1))); },',
    '    set(v) { this._base.fireCooldown = v; },',
    '});',
    '',
    '// Tower Defence liveConfig defaults (used by custom-DEFENSE section + sceneTowerDefense)',
    seg(lines, tdStart, tdEnd),
    '',
    '// ── GAME STATE (persists across scene restarts); guard allows inline fallback ──',
    preGuard,
    preTouch,
    preTheme,
    // clearTouchInput() only; the original `const gameTheme` line is dropped
    // because preTheme already declares it as a guarded fallback.
    seg(lines, clearStart, themeConst - 1),
    seg(lines, themeStart, themeEnd),
    '',
    seg(lines, tdDataStart, tdDataClose),
    '',
    'const _lcDefaults = JSON.parse(JSON.stringify(liveConfig));',
    '',
    'export { liveConfig, gameState, touchInput, gameTheme, themeInt, themeHex, _themeData, _lcDefaults, _clearTouchInput };',
    'export default liveConfig;',
    '',
  ].join(LF);
}

function buildGameAudio(html) {
  const lines = html.split(/\r?\n/);
  const start = exact(lines, 'const GameAudio = {');
  const end = findObjectEnd(lines, start);
  const prefixed = seg(lines, start, end).split(LF).map((l, i) => (i === 0 ? 'const GameAudio = {' : '    ' + l)).join(LF);
  return [
    '// GameAudio.js , GENERATED by scripts/sync-arcade-maker-modules.js from tools/arcade-game-maker.html.',
    '// Canonical ES-module form of the Web Audio SFX/music engine.',
    '// Do not hand-edit: edit the inline source and re-run the sync script.',
    '// Import: import { GameAudio } from "./GameAudio.js";',
    '',
    prefixed,
    '',
    'export { GameAudio };',
    'export default GameAudio;',
    '',
  ].join(LF);
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const stdout = args.includes('--stdout');
  const html = readHtml();

  // A760 and later: the modules are the source of truth. Once the inline
  // definitions are removed from the HTML there is nothing to re-extract, so
  // the sync becomes a no-op and the modules are left exactly as they are.
  if (!/^const\s+liveConfig\s*=\s*\{/m.test(html) || !/^const\s+GameAudio\s*=\s*\{/m.test(html)) {
    console.log('inline liveConfig/GameAudio no longer in tools/arcade-game-maker.html - modules are canonical, nothing to sync');
    return;
  }

  const outputs = {
    'liveConfig.js': buildLiveConfig(html),
    'GameAudio.js': buildGameAudio(html),
  };

  if (stdout) { Object.values(outputs).forEach(o => process.stdout.write(o)); return; }

  const dirty = [];
  for (const [name, content] of Object.entries(outputs)) {
    const file = path.join(SRC_DIR, name);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== content) dirty.push(name);
    if (!check) fs.writeFileSync(file, content, 'utf8');
  }

  if (check) {
    if (dirty.length) {
      console.log('OUT OF SYNC (run node scripts/sync-arcade-maker-modules.js): ' + dirty.join(', '));
      process.exit(1);
    }
    console.log('src/arcade-maker modules are in sync with tools/arcade-game-maker.html');
    return;
  }
  console.log(dirty.length ? 'wrote: ' + dirty.join(', ') : 'already in sync');
}

if (require.main === module) main();
module.exports = { buildLiveConfig, buildGameAudio };
