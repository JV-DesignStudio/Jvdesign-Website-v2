#!/usr/bin/env node
/**
 * scripts/workshop-gap-report.js (A3114 / A2031)
 *
 * Measures the progression gap instead of assuming it. Reads
 * content/workshops.json, maps each existing difficulty to the three-stage
 * rubric in content/workshop-stages.json, and writes
 * reports/workshop-gap-report.md grouped by engine and by tag.
 *
 * This script never edits a workshop and never changes a difficulty.
 *
 * Run:   node scripts/workshop-gap-report.js
 * Check: node scripts/workshop-gap-report.js --check
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const WORKSHOPS = path.join(ROOT, 'content', 'workshops.json');
const STAGES = path.join(ROOT, 'content', 'workshop-stages.json');
const OUT = path.join(ROOT, 'reports', 'workshop-gap-report.md');
const CHECK = process.argv.includes('--check');

const STAGE_ORDER = ['Beginner', 'Builder', 'Creator'];
const MAJOR_MIN = 5;

function load() {
  return {
    workshops: JSON.parse(fs.readFileSync(WORKSHOPS, 'utf8')),
    rubric: JSON.parse(fs.readFileSync(STAGES, 'utf8'))
  };
}

function emptyCounts() {
  return { Beginner: 0, Builder: 0, Creator: 0 };
}

function tally(list, keyFn, map) {
  const groups = new Map();
  for (const w of list) {
    const key = keyFn(w) || 'Untagged';
    if (!groups.has(key)) groups.set(key, { total: 0, ...emptyCounts() });
    const g = groups.get(key);
    const stage = map[w.difficulty] || 'Beginner';
    g.total++;
    g[stage]++;
  }
  return [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]));
}

function row(name, counts) {
  const gap = [];
  if (!counts.Builder) gap.push('Builder');
  if (!counts.Creator) gap.push('Creator');
  return '| ' + name + ' | ' + counts.total + ' | ' + counts.Beginner + ' | ' + counts.Builder + ' | ' +
    counts.Creator + ' | ' + (gap.length ? 'missing ' + gap.join(', ') : 'complete') + ' |';
}

function table(title, rows) {
  return [
    '### ' + title,
    '',
    '| ' + title.replace(/s$/, '') + ' | Workshops | Beginner | Builder | Creator | Gap |',
    '|---|---:|---:|---:|---:|---|',
    ...rows.map(([name, counts]) => row(name, counts)),
    ''
  ].join('\n');
}

function build() {
  const { workshops, rubric } = load();
  const map = rubric.mapping || {};
  const byEngine = tally(workshops, (w) => w.engine || 'General', map);
  const byTag = tally(workshops, (w) => (w.tags && w.tags[0]) || 'Untagged', map);

  const totals = emptyCounts();
  for (const w of workshops) totals[map[w.difficulty] || 'Beginner']++;

  const major = byEngine.filter(([, c]) => c.total >= MAJOR_MIN);
  const noBuilder = major.filter(([, c]) => !c.Builder).map(([name]) => name);
  const noCreator = major.filter(([, c]) => !c.Creator).map(([name]) => name);

  return [
    '# Workshop progression gap report',
    '',
    '> Generated by `scripts/workshop-gap-report.js` from `content/workshops.json` and the rubric in',
    '> `content/workshop-stages.json` (A3114 / A2031). Do not edit by hand: rerun the script.',
    '',
    '## The three stages',
    '',
    ...STAGE_ORDER.map((stage) => {
      const s = rubric.stages[stage];
      return '**' + stage + '**: ' + s.does + ' Support: ' + s.support + ' Evidence: ' + s.evidence;
    }),
    '',
    '## The gap in numbers',
    '',
    '| Stage | Workshops |',
    '|---|---:|',
    ...STAGE_ORDER.map((stage) => '| ' + stage + ' | ' + totals[stage] + ' |'),
    '',
    'Major subjects are engines with at least ' + MAJOR_MIN + ' workshops. ' +
      noBuilder.length + ' of ' + major.length + ' major engines have no Builder workshop. ' +
      noCreator.length + ' of ' + major.length + ' have no Creator workshop.',
    '',
    '## By engine',
    '',
    table('Engines', byEngine),
    '## By tag',
    '',
    table('Tags', byTag),
    '## Read this next',
    '',
    '- A missing Builder or Creator is a content gap, not a label to change.',
    '- Slices: A3115 fills the browser-first gap and A3116 fills the engine gap.',
    '- Use the rubric above to choose what the new workshop does, how much support it gives and what evidence it leaves.',
    ''
  ].join('\n');
}

function main() {
  const out = build();
  let have = '';
  try { have = fs.readFileSync(OUT, 'utf8'); } catch { /* first run */ }
  if (CHECK) {
    if (have !== out) {
      console.log('  [FAIL] workshop gap report is out of date: run node scripts/workshop-gap-report.js');
      process.exit(1);
    }
    console.log('  [PASS] workshop gap report is in sync');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  if (have !== out) fs.writeFileSync(OUT, out);
  console.log((have === out ? '  [PASS] workshop gap report already in sync' : '  [OK] wrote reports/workshop-gap-report.md'));
}

if (require.main === module) main();
module.exports = { build };
