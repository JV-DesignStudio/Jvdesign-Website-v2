#!/usr/bin/env node
/*
 * scripts/workshop-weight-report.js (A2339)
 *
 * Measures every workshop page and the workshop hub, then checks each one
 * against content/workshop-weight-budget.json. Raw HTML is the parse cost and
 * gzip is the transfer cost a school network actually pays.
 *
 * Run: node scripts/workshop-weight-report.js
 *      node scripts/workshop-weight-report.js --check   (CI: fail if over budget or stale)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.resolve(__dirname, '..');
const WS_DIR = path.join(ROOT, 'workshops');
const HUB = 'pages/workshop.html';
const BUDGET = path.join(ROOT, 'content', 'workshop-weight-budget.json');
const REPORT = path.join(ROOT, 'reports', 'workshop-weight.md');
const CHECK = process.argv.includes('--check');

const kb = (n) => Math.round(n / 1024);
const num = (n) => new Intl.NumberFormat('en-GB').format(n);

function pages() {
  const list = fs.readdirSync(WS_DIR)
    .filter((f) => f.endsWith('.html'))
    .map((f) => 'workshops/' + f);
  list.push(HUB);
  return list.sort();
}

function measure(rel) {
  const file = path.join(ROOT, rel);
  const buf = fs.readFileSync(file);
  const html = buf.toString('utf8');
  const inline = (html.match(/<script(?![^>]*\bsrc=)[^>]*>[\s\S]*?<\/script>/gi) || [])
    .reduce((n, block) => n + Buffer.byteLength(block), 0);
  return {
    rel,
    raw: buf.length,
    gzip: zlib.gzipSync(buf).length,
    inline,
    images: (html.match(/<img\b/gi) || []).length,
    tags: (html.match(/<[a-z][^>]*>/gi) || []).length
  };
}

function budgetFor(rel, budgets) {
  return budgets.pages[rel] || budgets.default;
}

function problems(row, budget) {
  const out = [];
  if (kb(row.raw) > budget.rawKB) out.push('raw ' + kb(row.raw) + 'KB > ' + budget.rawKB + 'KB');
  if (kb(row.gzip) > budget.gzipKB) out.push('gzip ' + kb(row.gzip) + 'KB > ' + budget.gzipKB + 'KB');
  if (kb(row.inline) > budget.inlineKB) out.push('inline ' + kb(row.inline) + 'KB > ' + budget.inlineKB + 'KB');
  if (row.images > budget.images) out.push('images ' + row.images + ' > ' + budget.images);
  if (row.tags > budget.tags) out.push('tags ' + row.tags + ' > ' + budget.tags);
  return out;
}

function render(rows, budgets) {
  const checked = rows.length;
  const over = rows.filter((r) => problems(r, budgetFor(r.rel, budgets)).length);
  const byRaw = rows.slice().sort((a, b) => b.raw - a.raw || a.rel.localeCompare(b.rel));
  const worstRaw = byRaw[0];
  const worstGzip = rows.slice().sort((a, b) => b.gzip - a.gzip || a.rel.localeCompare(b.rel))[0];
  const lines = [];
  lines.push('# Workshop page weight');
  lines.push('');
  lines.push('Generated by `scripts/workshop-weight-report.js`. Do not hand-edit.');
  lines.push('');
  lines.push('Every workshop page plus the hub is measured. Raw HTML is the parse cost,');
  lines.push('gzip is the transfer cost on a school network, and inline script bytes are');
  lines.push('the part that cannot be cached separately.');
  lines.push('');
  lines.push('## Budget');
  lines.push('');
  lines.push('| Page | Raw | Gzip | Inline script | Images | Tags |');
  lines.push('|---|---|---|---|---|---|');
  lines.push('| default | ' + budgets.default.rawKB + ' KB | ' + budgets.default.gzipKB + ' KB | ' +
    budgets.default.inlineKB + ' KB | ' + budgets.default.images + ' | ' + num(budgets.default.tags) + ' |');
  for (const rel of Object.keys(budgets.pages).sort()) {
    const b = budgets.pages[rel];
    lines.push('| ' + rel + ' | ' + b.rawKB + ' KB | ' + b.gzipKB + ' KB | ' + b.inlineKB + ' KB | ' +
      b.images + ' | ' + num(b.tags) + ' |');
  }
  lines.push('');
  lines.push('## Baseline');
  lines.push('');
  lines.push('- Pages checked: ' + num(checked));
  lines.push('- Over budget: ' + num(over.length));
  lines.push('- Heaviest raw: ' + worstRaw.rel + ' at ' + num(worstRaw.raw) + ' bytes (' + kb(worstRaw.raw) + ' KB)');
  lines.push('- Heaviest gzip: ' + worstGzip.rel + ' at ' + kb(worstGzip.gzip) + ' KB');
  lines.push('');
  lines.push('## All pages');
  lines.push('');
  lines.push('| Page | Raw KB | Gzip KB | Inline KB | Images | Tags | Status |');
  lines.push('|---|---:|---:|---:|---:|---:|---|');
  for (const row of byRaw) {
    const bad = problems(row, budgetFor(row.rel, budgets));
    lines.push('| ' + row.rel + ' | ' + kb(row.raw) + ' | ' + kb(row.gzip) + ' | ' + kb(row.inline) +
      ' | ' + row.images + ' | ' + num(row.tags) + ' | ' + (bad.length ? 'OVER: ' + bad.join('; ') : 'ok') + ' |');
  }
  lines.push('');
  return { markdown: lines.join('\n'), over };
}

function main() {
  const budgets = JSON.parse(fs.readFileSync(BUDGET, 'utf8'));
  const rows = pages().map(measure);
  const result = render(rows, budgets);

  if (CHECK) {
    let stale = '';
    try { stale = fs.readFileSync(REPORT, 'utf8'); } catch { stale = ''; }
    if (stale !== result.markdown) {
      console.error('workshop-weight-report: reports/workshop-weight.md is stale. Run node scripts/workshop-weight-report.js');
      return 1;
    }
    if (result.over.length) {
      console.error('workshop-weight-report: ' + result.over.length + ' page(s) over budget:');
      for (const row of result.over) {
        console.error(' - ' + row.rel + ': ' + problems(row, budgetFor(row.rel, budgets)).join('; '));
      }
      return 1;
    }
    console.log('PASS workshop-weight-report: ' + rows.length + ' pages inside budget');
    return 0;
  }

  fs.mkdirSync(path.dirname(REPORT), { recursive: true });
  fs.writeFileSync(REPORT, result.markdown);
  console.log('Wrote reports/workshop-weight.md');
  if (result.over.length) {
    for (const row of result.over) {
      console.log('OVER ' + row.rel + ': ' + problems(row, budgetFor(row.rel, budgets)).join('; '));
    }
  } else {
    console.log('All ' + rows.length + ' pages inside budget');
  }
  return result.over.length ? 1 : 0;
}

if (require.main === module) process.exit(main());

module.exports = { pages, measure, budgetFor, problems, render };
