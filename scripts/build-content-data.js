#!/usr/bin/env node
/**
 * build-content-data.js
 * Combines all content JSON files into a single JS file that
 * exposes window.JVDS_CONTENT for client-side use.
 *
 * Output: /content-data.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONTENT = path.join(ROOT, 'content');

const files = ['workshops', 'games', 'tools', 'books', 'characters', 'paths', 'stats'];
const data = {};

for (const name of files) {
  const filePath = path.join(CONTENT, `${name}.json`);
  if (fs.existsSync(filePath)) {
    data[name] = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  }
}

// Workshop cover fallback , if cover is null and og/{id}.png exists, use it so workshop hub doesn't render placeholder-only
if (Array.isArray(data.workshops)) {
  data.workshops = data.workshops.map(w => {
    if (w.cover) return w;
    const ogPng = path.join(ROOT, 'og', `${w.id}.png`);
    const ogWebp = path.join(ROOT, 'og', `${w.id}.webp`);
    if (fs.existsSync(ogPng)) return { ...w, cover: `og/${w.id}.png` };
    if (fs.existsSync(ogWebp)) return { ...w, cover: `og/${w.id}.webp` };
    // fallback to generic workshop og
    if (fs.existsSync(path.join(ROOT, 'og', 'learn.png'))) return { ...w, cover: `og/learn.png` };
    if (fs.existsSync(path.join(ROOT, 'og', 'hub-games.png'))) return { ...w, cover: `og/hub-games.png` };
    return w;
  });
}

const output = `// Auto-generated by build-content-data.js , do not edit manually
// Run: node scripts/build-content-data.js
window.JVDS_CONTENT = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(path.join(ROOT, 'content-data.js'), output);
console.log(`Built content-data.js (${(output.length / 1024).toFixed(1)} KB)`);
