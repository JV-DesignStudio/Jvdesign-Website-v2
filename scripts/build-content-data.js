#!/usr/bin/env node
/**
 * build-content-data.js
 * Combines all content JSON files into a single JS file that
 * exposes window.JVDS_CONTENT for client-side use.
 *
 * Output: /content-data.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CONTENT = path.join(ROOT, 'content');

const files = ['workshops', 'games', 'tools', 'books', 'characters', 'paths', 'stats'];
const data = {};

for (const name of files) {
  const filePath = path.join(CONTENT, `${name}.json`);
  if (fs.existsSync(filePath)) {
    data[name] = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  }
}

const output = `// Auto-generated by build-content-data.js — do not edit manually
// Run: node scripts/build-content-data.js
window.JVDS_CONTENT = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(path.join(ROOT, 'content-data.js'), output);
console.log(`Built content-data.js (${(output.length / 1024).toFixed(1)} KB)`);
