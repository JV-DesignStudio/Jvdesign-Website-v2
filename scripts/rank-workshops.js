#!/usr/bin/env node
/*
 * scripts/rank-workshops.js (A2642)
 *
 * Ranks the workshop catalogue by evidence of quality and uniqueness so the
 * weakest entries can be reviewed for retirement, merge or a legacy flag.
 *
 * It is deliberately conservative: browser/school-PC workshops, first-series
 * landing pages, course steps, browser studios and reference cheat sheets are
 * protected and never recommended for removal. "Weak" here means thin or
 * duplicated, not "unpopular".
 *
 * Run: node scripts/rank-workshops.js
 * Writes: reports/workshop-cull-ranking.md
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const readJson = (rel, fallback) => {
  try { return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); } catch { return fallback; }
};

const cat = readJson('content/workshops.json', []);
const completion = readJson('content/workshop-completion.json', { workshops: [] }).workshops || [];
const outcomesRaw = readJson('content/workshop-outcomes.json', []);
const outcomes = Array.isArray(outcomesRaw) ? outcomesRaw : outcomesRaw.workshops || [];
const needs = readJson('content/workshop-needs.json', []);
const courses = readJson('content/courses.json', { courses: [] }).courses || [];

const compById = new Map(completion.map((c) => [c.id, c]));
const outById = new Map(outcomes.map((o) => [o.id, o]));
const needsById = new Map(needs.map((n) => [n.id, n]));
const courseIds = new Set();
for (const c of courses) for (const s of c.steps || []) if (s && s.slug) courseIds.add(s.slug);

const SCHOOL_PC_ENGINES = new Set(['Scratch', 'JavaScript', 'General', 'TinkerCAD']);
const CONCEPTS = ['platformer', 'shooter', 'pong', 'rpg', 'breakout', 'snake', 'maze', 'clicker', 'racing', 'tower', 'match', 'dungeon', 'flappy', 'quiz', 'catch', 'dodge'];
const conceptOf = (e) => {
  const s = (e.title + ' ' + e.id).toLowerCase();
  return CONCEPTS.find((k) => s.includes(k)) || null;
};
const conceptKey = (e) => { const c = conceptOf(e); return c ? e.engine + '|' + c : null; };
const conceptCount = {};
for (const e of cat) { const k = conceptKey(e); if (k) conceptCount[k] = (conceptCount[k] || 0) + 1; }

const isStudio = (id) => /-(?:mod-)?studio$/.test(id);
const isReference = (id) => /-cheatsheet$/.test(id);
const isSetupHelper = (id) => /starter|setup-check|visuals/.test(id);

function protectedReason(e) {
  if (courseIds.has(e.id)) return 'step in a course';
  if (e.id.startsWith('my-first-')) return 'first-series landing';
  const n = needsById.get(e.id);
  if (n && n.needs === 'browser' && SCHOOL_PC_ENGINES.has(e.engine)) return 'school-PC browser workshop';
  if (isStudio(e.id)) return 'browser studio';
  if (isReference(e.id)) return 'reference cheat sheet';
  if (isSetupHelper(e.id)) return 'setup helper';
  return null;
}

const rows = cat.map((e) => {
  const comp = compById.get(e.id);
  const out = outById.get(e.id);
  const reasons = [];
  let score = 0;
  if (!comp) { score += 3; reasons.push('no completion contract'); }
  else if (comp.hasFinishBanner === false) { score += 1; reasons.push('no finish banner'); }
  if (!out) { score += 2; reasons.push('no outcome'); }
  if (!e.steps) { score += 2; reasons.push('0 steps'); }
  if (!e.cover) { score += 1; reasons.push('no cover'); }
  const ck = conceptKey(e);
  if (ck && conceptCount[ck] > 1) { score += 1; reasons.push('same concept as another ' + e.engine + ' course'); }
  if (/-canvas$/.test(e.id)) { score += 1; reasons.push('canvas build-along'); }
  if (/-part\d$/.test(e.id)) { score += 1; reasons.push('series part'); }
  if ((e.desc || '').length < 40) { score += 1; reasons.push('short description'); }
  const prot = protectedReason(e);
  return { e, score, reasons, prot, hasComp: !!comp, hasOutcome: !!out };
});

// Weakest first, but never recommend a protected entry for removal.
const ranked = [...rows].sort((a, b) => b.score - a.score || a.e.title.localeCompare(b.e.title));
const candidates = ranked.filter((r) => !r.prot);
const target = Math.ceil(cat.length * 0.2);
const firstSlice = candidates.filter((r) => /-canvas$/.test(r.e.id));
const shortlist = candidates.slice(0, target);

const byEngine = {};
for (const e of cat) byEngine[e.engine] = (byEngine[e.engine] || 0) + 1;

const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|');
const lines = [];
lines.push('# Workshop cull ranking (A2642)', '');
lines.push('Generated by `node scripts/rank-workshops.js` from the 20 November 2026 catalogue.', '');
lines.push(`- Catalogue entries: **${cat.length}**`);
lines.push(`- Protected from removal: **${rows.filter((r) => r.prot).length}** (course steps, first-series landings, school-PC browser workshops, browser studios, cheat sheets, setup helpers)`);
lines.push(`- 20% target: **${target}**`);
lines.push(`- High-confidence duplicate slice (canvas build-alongs with a guide): **${firstSlice.length}**`);
lines.push(`- Entries with a completion contract: **${completion.length}**; with an outcome: **${outcomes.length}**`, '');
lines.push('"Weak" here means thin or duplicated. It does not mean unpopular: there is no per-learner completion analytics on disk.', '');
lines.push('## Engines', '');
lines.push('| Engine | Workshops |', '| --- | ---: |');
for (const [eng, n] of Object.entries(byEngine).sort((a, b) => b[1] - a[1])) lines.push(`| ${esc(eng)} | ${n} |`);
lines.push('');

lines.push('## Ranked, weakest first', '');
lines.push('| # | Score | Workshop | Engine | Protected | Signals |');
lines.push('| ---: | ---: | --- | --- | --- | --- |');
ranked.forEach((r, i) => {
  lines.push(`| ${i + 1} | ${r.score} | [${esc(r.e.title)}](${r.e.url}) | ${esc(r.e.engine)} | ${r.prot ? esc(r.prot) : ''} | ${esc(r.reasons.join('; '))} |`);
});
lines.push('');

lines.push('## Recommended first slice (safe to collapse under its guide)', '');
lines.push('These are canvas build-alongs whose guide workshop already sits in the catalogue. They keep working; the hub can list them under a "Build it in the browser" group instead of the main grid.', '');
for (const r of firstSlice) lines.push(`- [${esc(r.e.title)}](${r.e.url}) (${esc(r.e.engine)})`);
lines.push('');

lines.push('## Needs a human call (next weakest, protected entries excluded)', '');
lines.push('Retiring or merging these changes what a learner can choose, so they are listed for sign-off rather than applied automatically.', '');
for (const r of shortlist) lines.push(`- ${esc(r.e.id)}: ${esc(r.e.title)} (${esc(r.e.engine)}, score ${r.score})${r.reasons.length ? ' - ' + esc(r.reasons.join('; ')) : ''}`);

const outPath = path.join(ROOT, 'reports', 'workshop-cull-ranking.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n');

console.log(`Ranked ${cat.length} workshops.`);
console.log(`Protected: ${rows.filter((r) => r.prot).length}. 20% target: ${target}.`);
console.log(`Safe duplicate slice (canvas with guide): ${firstSlice.length}.`);
console.log(`Wrote reports/workshop-cull-ranking.md`);
